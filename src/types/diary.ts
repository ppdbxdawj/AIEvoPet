/**
 * Diary types live in their own file because the diary ledger grows
 * independently of pet.json -- it's persisted to a separate diary.json on
 * disk so weeks of activity tracking don't bloat the pet snapshot we
 * round-trip through every commit.
 *
 * Append-only semantics: closed days are frozen. A given date can be
 * re-rolled (the "today draft" pattern) until midnight rolls past, after
 * which the entry is sealed. The Rust side enforces this on save by
 * rejecting writes whose previous-day entries differ from the on-disk copy.
 */

/** Per-repo commit slice for a given date. */
export interface PetDiaryGitRepoStat {
  // Absolute path on disk; we hash this for display in the UI but keep it
  // here so the user can spot which repo a number came from.
  path: string
  // Commit count authored on the date (regardless of author). Multi-author
  // counts are intentional -- we want the "what happened to this codebase
  // today" view, not "how many of these were mine".
  commits: number
  // Lines added/removed across all commits on this date. -1 when the repo
  // failed to read (e.g. shallow clone, permission error, not a git repo);
  // the UI surfaces the failure rather than guessing.
  insertions: number
  deletions: number
  // First and last commit subject lines, used by the diary narrative as
  // anchor moments. Empty when no commits.
  firstSubject?: string
  lastSubject?: string
  error?: string
}

export interface PetDiaryGitStats {
  // Aggregated across all repos.
  totalCommits: number
  totalInsertions: number
  totalDeletions: number
  perRepo: PetDiaryGitRepoStat[]
}

export interface PetDiaryActivityStats {
  // Total minutes of "user was active at the keyboard/mouse" on this date,
  // measured by sampling the system idle counter. -1 means tracking was
  // disabled or the platform sampler failed.
  activeMinutes: number
  // First active sample of the day (HH:mm), helps the narrative say
  // "today you started early" when relevant.
  firstActiveAt?: string
  lastActiveAt?: string
  // Whether the sampler was actually running for the full day. False values
  // tell the UI to soften any conclusions ("part-day data only").
  fullDayCoverage: boolean
}

export interface PetDiaryMemorableEvent {
  id: string
  ts: string
  type: string
  summary: string
  importance: 1 | 2 | 3
  category?: string
}

export interface PetDiaryConversationStats {
  // Number of user-initiated messages. Drawn from pet.memory.events of
  // type 'chat' filtered by date.
  userMessages: number
  // Total characters typed by the user across the day.
  userCharacters: number
  // Bubble responses the pet emitted (chat + scene + reminder bubbles).
  petBubbles: number
  // Count of importance>=2 events touched today.
  importantEvents: number
  memorableEvents?: PetDiaryMemorableEvent[]
  // Top 3 categories the day's events fell into (memory categorisation
  // from the event-extraction layer).
  topCategories: string[]
}

export type PetDiarySource = 'auto' | 'manual'

/**
 * One full chat turn captured verbatim for today's draft. Used as the
 * short-term memory that feeds the diary narrative + accurate conversation
 * stats. Dropped when the day gets sealed -- the seal step is the
 * "summarised, then destroyed" boundary.
 */
export interface PetDiaryRawTurn {
  ts: string
  role: 'user' | 'pet'
  text: string
  // Where the turn originated. 'chat' is the usual conversation; 'coding'
  // is reserved for bridge events (Cursor / Claude Code) so they can be
  // told apart in the narrative.
  source: 'chat' | 'coding'
}

export interface PetDiaryEntry {
  // ISO date YYYY-MM-DD. Primary key in the ledger.
  date: string
  // Wall-clock timestamp this entry was last refreshed. For a sealed day
  // this is the timestamp it was sealed at; for the today draft it updates
  // each rollup tick.
  refreshedAt: string
  // True once midnight passes and the entry is frozen against further
  // automatic rewrites. Manual user notes can still be appended.
  sealed: boolean
  // Was this date generated by the auto rollup or stitched together by a
  // user-driven action (export, manual roll, etc).
  source: PetDiarySource
  // Free-form narrative, ideally LLM-written. The deterministic fallback
  // is also stored here so the UI never shows a blank day.
  narrative: string
  // True iff the narrative came from the LLM path; UI dims/marks the
  // fallback so the user can ask for a re-roll.
  narrativeSource: 'model' | 'fallback'
  modelNarrativeAt?: string
  modelNarrativeTurnCount?: number
  modelNarrativeImportantEvents?: number
  conversation: PetDiaryConversationStats
  git: PetDiaryGitStats
  activity: PetDiaryActivityStats
  // Optional user-added note appended to the entry. Survives auto-rewrites
  // even on the today draft -- we splice it into a separate field so the
  // narrative regen never destroys it.
  userNote?: string
  // Pet-side aggregates pulled from memory.events / memory.daily on this
  // date. Cheap to recompute but cached on the entry so historical days
  // remain stable even after events scroll out of the working set.
  petDailySummary?: string
  petDominantMood?: string
  // Today's full chat transcript. Kept while the day is open so the
  // narrative regen has the actual words; dropped at seal time so old
  // diary files don't grow unbounded. Optional for backwards compat.
  rawTurns?: PetDiaryRawTurn[]
}

/** Top-level configuration the user controls from the settings tab. */
export interface PetDiaryConfig {
  // List of absolute repo paths the user has opted in to track. We
  // intentionally store paths verbatim (not symlink-resolved) so the user's
  // mental model matches what they see.
  gitRepoPaths: string[]
  // Master switch for the system idle sampler. When false, no Tauri-side
  // sampler ever runs and the activity stats record -1.
  activityTrackingEnabled: boolean
  // Optional throttle on how often we re-roll today's diary draft when the
  // user is actively chatting. Default 60 minutes, minimum 10.
  todayRollupIntervalMinutes: number
}

export interface PetDiaryLedger {
  // Map keyed by date (YYYY-MM-DD). Stored as an object rather than an
  // array because look-up by date is the only access pattern; we sort
  // back into an array on read.
  entries: Record<string, PetDiaryEntry>
  config: PetDiaryConfig
  // Schema version for forward-compatible migrations. Bump on any breaking
  // change to PetDiaryEntry.
  schemaVersion: number
  // Creation stamp; nudges some UI copy ("陪伴第 N 天的日记").
  createdAt: string
}

export const PET_DIARY_SCHEMA_VERSION = 1

export const createDefaultDiaryConfig = (): PetDiaryConfig => ({
  gitRepoPaths: [],
  activityTrackingEnabled: false,
  todayRollupIntervalMinutes: 60
})

export const createDefaultDiaryLedger = (now = Date.now()): PetDiaryLedger => ({
  entries: {},
  config: createDefaultDiaryConfig(),
  schemaVersion: PET_DIARY_SCHEMA_VERSION,
  createdAt: new Date(now).toISOString()
})
